    fun getTechsForPreset(presetName: String): Map<String, Boolean> {
        val cleanPreset = presetName.removeSuffix("+")
        val reqIndex = PRESET_ORDER.indexOfFirst { it.equals(presetName, ignoreCase = true) || it.equals(cleanPreset, ignoreCase = true) }
            .let { if (it < 0) 3 else it }
        return ALL_TECHS.associate { tech ->
            val techClean = tech.minPreset.removeSuffix("+")
            val techIndex = PRESET_ORDER.indexOfFirst { it.equals(tech.minPreset, ignoreCase = true) || it.equals(techClean, ignoreCase = true) }
                .let { if (it < 0) 3 else it }
            tech.name to (techIndex <= reqIndex)
        }
    }
